// Kanji list data for みる / おぼえる / かく tabs

class KanjiItem {
  final String kanji;
  final String kunYomi;      // 訓読み (primary, used in みる/おぼえる/かく)
  final String onYomi;       // 音読み
  final String meaning;
  final int grade;
  final String example;      // 使い方の例
  final String exampleReading; // 例文のよみかた (ふりがな)
  final String description;  // 漢字の説明・由来

  const KanjiItem({
    required this.kanji,
    required this.kunYomi,
    required this.onYomi,
    required this.meaning,
    required this.grade,
    required this.example,
    required this.exampleReading,
    this.description = '',
  });

  /// みる画面に表示するよみ（くんよみ / おんよみ）
  String get displayReading {
    if (onYomi.isEmpty) return kunYomi;
    if (kunYomi.isEmpty) return onYomi;
    return '$kunYomi / $onYomi';
  }
}

