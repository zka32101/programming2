/// 学年コードのユーティリティ。
///
/// grade コード: 0=小学未満 / 1〜6=小学1〜6年生 / 7=中学以上
/// ステージ選択・出題ロジックは小学1〜6年生の範囲のみ対応しているため、
/// 0 や 7 が入力された場合は範囲内にクランプして使用する。

/// 画面表示用の学年ラベルを返す。
String gradeLabel(int grade) {
  if (grade <= 0) return '小学未満';
  if (grade >= 7) return '中学以上';
  return '小学$grade年生';
}

/// ステージ選択・出題生成など「小学1〜6年生」の範囲を前提とする処理向けに
/// 学年コードを 1〜6 にクランプする。
int clampToStageGrade(int grade) => grade.clamp(1, 6);
